"""en-affix test cfgs (home_test): python tools/affix_fixtures/gen.py -> tools/affix_fixtures/*.cfg.
cfg `wait` measured at ~200 frames a second here (2x the com_maxfps 100 guess): W(sec) = sec * 20 'wait 10' lines."""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent


def W(sec):
    return ['wait 10'] * max(1, int(sec * 20))


def shot():
    return ['screenshotJPEG'] + W(0.4)


def head():
    return ['// en-affix test (generated by gen.py)', 'set com_maxfps 100', 'set cg_drawFPS 0', 'set g_dsStagger 0'] + W(6)


# tells + mechanics: bots fight with affixes, then one affix per bot for the pictures, explode / split,
# a champion pack, the frost edge and TAB
def tells():
    c = head()
    c += ['god', 'dsaffixstate']
    c += ['dsaffix set all vampiric frost reflect'] + W(25)
    c += ['dsaffix set all fire regen pull'] + W(20)
    c += ['dsaffixstate', 'bot_pause 1'] + W(1)
    # one tell per bot, close up
    for k, aff in ((1, 'vampiric'), (2, 'frost'), (3, 'fire'), (4, 'split')):
        c += ['dsaffix set %i %s' % (k, aff), 'dsaffix look %i 120' % k] + W(1.6) + shot()
    for k, aff in ((1, 'explode'), (2, 'reflect'), (4, 'regen')):
        c += ['dsaffix set %i %s' % (k, aff), 'dsaffix look %i 120' % k] + W(1.6)
        if aff == 'reflect':
            c += ['dsaffix hurt 2 20'] + W(0.05)
        if aff == 'regen':
            c += ['dsaffix hurt 4 60'] + W(5)
        c += shot()
    # MAGNETIC wind-up: look from 450 units
    c += ['dsaffix set 3 pull', 'dsaffix look 3 450'] + W(7) + ['dsaffixstate'] + W(0.1)
    # the stack: three affixes on one bot
    c += ['dsaffix set 1 vampiric frost fire', 'dsaffix look 1 130'] + W(1.6) + shot()
    # explosive + splitting death (as if you killed it)
    c += ['dsaffix set 1 explode split frost', 'dsaffix look 1 320'] + W(1)
    c += ['dsaffix kill 1'] + W(0.7) + shot() + W(0.5) + shot() + W(1.2) + shot()
    c += ['dsaffixstate'] + W(0.5)
    # the frost edge on your screen
    c += ['dsaffix frost'] + W(0.3) + shot()
    # TAB
    c += ['+scores'] + W(0.6) + shot() + ['-scores']
    # a champion pack
    c += ['bot_pause 0', 'dschampions frost fire'] + W(0.5) + ['dsaffix lookpack'] + W(0.8) + shot()
    c += W(2.6) + shot() + W(1.5) + shot() + ['dsaffixstate'] + W(8) + ['dsaffixstate']
    c += ['quit']
    return c


# natural play: the floor's own elite (rolled affixes) and an affixed field against you, no god;
# then a champion pack fought for real; numbers come from games.log
def mech():
    c = head()
    c += ['dsaffixstate', 'dsaffix set all vampiric frost reflect fire regen pull'] + W(45)
    c += ['dsaffixstate', 'dschampions'] + W(40)
    c += ['dsaffixstate', 'quit']
    return c


# clean pictures: bots frozen right away (no fire patches lying around), one affix at a time on the
# same bot, seen from 110 units, then a pull wind-up from 420
def pics():
    c = head()
    c += ['god'] + W(3) + ['bot_pause 1', 'dsaffix set all none'] + W(1)
    for aff in ('vampiric', 'explode', 'split', 'reflect', 'frost', 'fire', 'regen', 'vampiric frost fire'):
        c += ['dsaffix set 2 %s' % aff, 'dsaffix look 2 110'] + W(1.5)
        if aff == 'reflect':
            c += ['dsaffix hurt 2 15'] + W(0.03)
        if aff == 'regen':
            c += ['dsaffix hurt 2 40'] + W(4.6)
        c += shot()
    c += ['dsaffix set 2 none', 'dsaffix set 3 pull', 'dsaffix look 3 420'] + W(2.5)
    for _ in range(12):
        c += W(0.25) + ['screenshotJPEG']
    c += ['dsaffixstate', 'quit']
    return c


# vampire close-up over time, then with the tells off (what tints the scene?)
def vamp():
    c = head()
    c += ['god'] + W(3) + ['bot_pause 1', 'dsaffix set all none'] + W(1)
    c += ['dsaffix set 2 vampiric', 'dsaffix look 2 110']
    for _ in range(6):
        c += W(0.5) + ['screenshotJPEG']
    c += ['set cg_dsAffixTells 2'] + W(1.5) + ['screenshotJPEG'] + W(0.3)
    c += ['set cg_dsAffixTells 0'] + W(1.5) + ['screenshotJPEG'] + W(0.3)
    c += ['set cg_dsAffixTells 1', 'dsaffix set 2 regen', 'dsaffix hurt 2 40'] + W(5) + ['screenshotJPEG'] + W(0.3)
    c += ['dsaffixstate', 'quit']
    return c


# live (unpaused) close-ups: the thinner vampire mist, then a MAGNETIC bot's wind-up and yank
def live():
    c = head()
    c += ['god', 'dsaffix set all none'] + W(2)
    c += ['dsaffix set 2 vampiric', 'dsaffix look 2 130'] + W(0.3) + ['screenshotJPEG'] + W(0.3) + ['dsaffix look 2 130'] + W(0.3) + ['screenshotJPEG']
    c += ['dsaffix set 2 none', 'dsaffix set 3 pull']
    for _ in range(10):
        c += ['dsaffix look 3 500'] + W(0.35) + ['screenshotJPEG'] + W(0.35) + ['screenshotJPEG']
    c += ['dsaffixstate', 'quit']
    return c


# the roster's rolled affixes only (RUN=run_elite2.txt / run_elite20.txt for acts 1 / 4)
def roll():
    return head() + ['dsaffixstate'] + W(1) + ['quit']


# the versus intro / arrival strip with the elite's affixes under its portrait (cg_dsIntro 1)
def intro():
    c = ['// en-affix intro pictures', 'set com_maxfps 100']
    for _ in range(30):
        c += W(0.8) + ['screenshotJPEG']
    return c + ['quit']


# you in the line of fire: every 2 s you stand in front of a bot (no god); FROST / VAMPIRIC hits on you
def hits():
    c = head() + ['dsaffix set all frost vampiric']
    for k in range(18):
        c += ['dsaffix look %i 260' % (1 + k % 4)] + W(1.2) + (['screenshotJPEG'] if k % 3 == 2 else []) + W(0.8)
    c += ['dsaffixstate', 'quit']
    return c


# a champion pack you destroy (dev kills as if by you): the rewards
def champ():
    c = head() + ['god', 'dschampions'] + W(4.5) + ['dsaffixstate']
    for k in (5, 6, 7):
        c += ['dsaffix kill %i' % k] + W(0.6)
    c += W(2) + ['dsaffixstate', 'quit']
    return c


if __name__ == '__main__':
    for name, fn in (('tells.cfg', tells), ('mech.cfg', mech), ('pics.cfg', pics), ('vamp.cfg', vamp), ('live.cfg', live), ('roll.cfg', roll), ('intro.cfg', intro), ('hits.cfg', hits), ('champ.cfg', champ)):
        (HERE / name).write_text('\n'.join(fn()) + '\n')
    print('written', [p.name for p in HERE.glob('*.cfg')])
