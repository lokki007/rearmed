"""Write assets/scripts/rearmed_v4.shader (shaders for every v4 model surface + gore texture)."""
import pathlib

OUT = pathlib.Path(__file__).resolve().parent.parent.parent / 'assets' / 'scripts' / 'rearmed_v4.shader'


def opaque(name, tex=None):
    tex = tex or name + '.tga'
    return f"""{name}
{{
	{{
		map {tex}
		rgbGen lightingDiffuse
	}}
}}
"""


def wet(name, tex=None, env='models/rearmed/gibs/wetenv.tga'):
    # base flesh + an additive environment-mapped sheen so gibs look wet and glossy
    tex = tex or name + '.tga'
    return f"""{name}
{{
	{{
		map {tex}
		rgbGen lightingDiffuse
	}}
	{{
		map {env}
		blendFunc GL_ONE GL_ONE
		tcGen environment
		rgbGen lightingDiffuse
	}}
}}
"""


def decal(name):
    # world decal (CG_ImpactMark): alpha blended, colour/fade from the mark's vertex colours
    return f"""{name}
{{
	nopicmip
	polygonOffset
	{{
		clampmap {name}.tga
		blendFunc GL_SRC_ALPHA GL_ONE_MINUS_SRC_ALPHA
		rgbGen vertex
		alphaGen vertex
	}}
}}
"""


def screen(name):
    # 2D overlay (trap_R_DrawStretchPic): colour/alpha from trap_R_SetColor
    return f"""{name}
{{
	nopicmip
	nomipmaps
	{{
		clampmap {name}.tga
		blendFunc GL_SRC_ALPHA GL_ONE_MINUS_SRC_ALPHA
		rgbGen vertex
		alphaGen vertex
	}}
}}
"""


# id-style shiny model: a lit environment stage under the base texture, whose alpha (1 - shine) lets the
# sheen through on oil, brass and glass only; then a slow additive glow (barrel crack, tank sight glass)
PROP_SHINY = """models/rearmed/props/{n}
{{
	{{
		map models/rearmed/props/propenv.tga
		tcGen environment
		rgbGen lightingDiffuse
	}}
	{{
		map models/rearmed/props/{n}.tga
		blendFunc GL_SRC_ALPHA GL_ONE_MINUS_SRC_ALPHA
		rgbGen lightingDiffuse
	}}
	{{
		map models/rearmed/props/{n}_glow.tga
		blendFunc GL_ONE GL_ONE
		rgbGen wave sin {wave}
	}}
}}
"""


METEOR = """models/rearmed/meteor
{
	{
		map models/rearmed/meteor.tga
		rgbGen lightingDiffuse
	}
	{
		map models/rearmed/meteor_glow.tga
		blendFunc GL_ONE GL_ONE
		rgbGen wave sin 0.85 0.3 0 1.3
	}
}
"""


def main():
    parts = ['// REARMED v4 models + gore textures (generated by tools/blender/make_shader.py; do not edit by hand)\n']
    parts.append(PROP_SHINY.format(n='barrel', wave='0.7 0.3 0 0.55'))
    parts.append(opaque('models/rearmed/props/crate'))
    parts.append(PROP_SHINY.format(n='tank', wave='0.75 0.25 0.37 0.3'))
    for d in ('rock', 'metal', 'wood'):
        parts.append(opaque('models/rearmed/debris/' + d))
    for i in range(1, 7):
        parts.append(wet(f'models/rearmed/gibs/meat{i}'))
    parts.append(wet('models/rearmed/gibs/head', env='models/rearmed/gibs/wetenv_dim.tga'))
    parts.append(METEOR)
    for i in range(1, 5):
        parts.append(decal(f'gfx/rearmed/gore/splat{i}'))
    parts.append(decal('gfx/rearmed/gore/drip'))
    for i in range(1, 4):
        parts.append(screen(f'gfx/rearmed/gore/screen{i}'))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    # CRLF like the rest of the tree
    OUT.write_bytes('\n'.join(parts).replace('\n', '\r\n').encode('ascii'))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
