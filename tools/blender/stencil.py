def text_mask(txt, w, h, cx, cy, cell, out):
    """Stamp stencil text (centred at cx,cy in pixels, `cell` px per glyph pixel) into mask `out`."""
    gw = len(txt) * 6 * cell - cell
    x0 = int(cx - gw / 2)
    y0 = int(cy - 7 * cell / 2)
    for i, ch in enumerate(txt):
        g = FONT.get(ch, FONT[' '])
        for r, row in enumerate(g):
            for c, bit in enumerate(row):
                if bit == '1':
                    xa = x0 + (i * 6 + c) * cell
                    ya = y0 + r * cell
                    # stencil: tiny gaps between cells so it reads as sprayed through a stencil
                    out[max(ya, 0):max(ya + cell, 0), max(xa, 0):max(xa + cell - max(1, cell // 6), 0)] = 1.0
