# generates tools/clip_cfgs/alt.cfg: one demo per alt-fire (alt_a..alt_f), map_restart between them.
# wait = ~4 ms (fixedtime 8, 2 waits a frame): 250 waits = 1 s
import os
P = "1350 -60 -39"
segs = [
 # name, weapon, bots [(x,y,yaw)], player yaw pitch, action lines
 ("alt_a", 4, [(1170,-60,0)], 180, 1, ["+button12", "wait 25", "-button12", "wait 450"]),
 ("alt_b", 5, [(1090,-5,0), (1090,-115,0)], 180, 0, ["+attack", "wait 4", "-attack", "wait 66", "+button12", "wait 25", "-button12", "wait 330"]),
 ("alt_c", 6, [(1110,-60,0), (1050,40,0), (1050,-160,0)], 180, 0, ["+button12", "wait 25", "-button12", "wait 110", "+button12", "wait 25", "-button12", "wait 110", "+button12", "wait 25", "-button12", "wait 200"]),
 ("alt_d", 7, [(1160,-60,0), (950,-60,0)], 180, 9, ["+button12", "wait 25", "-button12", "wait 330"]),
 ("alt_e", 8, [(1120,-20,0), (1120,-100,0), (1060,-60,0)], 180, 6, ["+button12", "wait 310", "-button12", "wait 420"]),
 ("alt_f", 9, [(950,-60,0), (952,-18,0), (952,-102,0)], 180, 0, ["+button12", "wait 25", "-button12", "wait 380"]),
]
L = ["// promo clips: alt-fire montage, generated by tools/clip_gen/gen_alt.py", "wait 100", "exec clip_common.cfg",
     "set cg_killCam 0", "set g_rearmMode 0", "set fraglimit 0", "set bot_pause 1",
     "addbot sarge 1", "addbot doom 1", "addbot klesk 1", "wait 300"]
for i, (name, w, bots, yaw, pitch, act) in enumerate(segs):
    if i:
        L += ["map_restart 0", "wait 300", "kick allbots", "wait 100", "addbot sarge 1", "addbot doom 1", "addbot klesk 1", "wait 400", "set bot_pause 1", "wait 50"]
    L += ["god", "give all", "wait 30", "weapon %d" % w, "teleport 0 %s %d %d" % (P, yaw, pitch)]
    for b in range(3):
        if b < len(bots):
            x, y, by = bots[b]
            L += ["teleport %d %d %d -39 %d" % (b + 1, x, y, by)]
        else:
            L += ["teleport %d 600 -900 -39 0" % (b + 1)]
    L += ["wait 300"]
    for b in range(len(bots)):
        L += ["kchurt %d 0 %d 1" % (b + 1, 50 if name == "alt_c" else 64)]
    L += ["wait 200", "record " + name, "wait 420"] + act + ["stoprecord", "wait 20"]
L += ["quit"]
open(os.path.join(os.path.dirname(__file__), "..", "clip_cfgs", "alt.cfg"), "w").write("\n".join(L) + "\n")
