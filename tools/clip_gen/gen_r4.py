def rec(name, setup, act, secs, lead=1.6):
    # setup (weapon switch etc.) 2 s before the demo starts, then a lead so the weapon bar is gone at the action
    return ['bot_pause 1'] + setup + W(2.0) + ['record ' + name] + W(lead) + act + W(secs) + ['stoprecord', 'bot_pause 1'] + W(0.3)


