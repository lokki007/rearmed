"""Screen-effect textures + shaders for the random events and slow motion
(gfx/rearmed/events/*.tga, scripts/rearmed_events.shader). Events worker, v4."""
import math, pathlib, random
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent / 'assets'
GFX = ROOT / 'gfx' / 'rearmed' / 'events'


def smooth(a, b, x):
    t = max(0.0, min(1.0, (x - a) / (b - a)))
    return t * t * (3 - 2 * t)


def save_alpha(name, size, fn):
    """white texture, the function gives the alpha"""
    w, h = size
    im = Image.new('RGBA', size)
    px = im.load()
    for y in range(h):
        for x in range(w):
            a = max(0.0, min(1.0, fn((x + 0.5) / w, (y + 0.5) / h)))
            px[x, y] = (255, 255, 255, int(a * 255 + 0.5))
    GFX.mkdir(parents=True, exist_ok=True)
    im.save(GFX / name)


def save_grey(name, size, fn):
    """grey value texture (for additive blends)"""
    w, h = size
    im = Image.new('RGBA', size)
    px = im.load()
    for y in range(h):
        for x in range(w):
            v = int(max(0.0, min(1.0, fn((x + 0.5) / w, (y + 0.5) / h))) * 255 + 0.5)
            px[x, y] = (v, v, v, 255)
    GFX.mkdir(parents=True, exist_ok=True)
    im.save(GFX / name)


# radial vignette: clear middle, dark corners (stretched to any aspect, so work in uv)
def vignette(u, v):
    x, y = (u - 0.5) * 2, (v - 0.5) * 2
    r = math.sqrt(x * x * 0.8 + y * y)
    return smooth(0.45, 1.25, r) ** 1.3


# warm glow falling from the top edge (meteor sky)
def topglow(u, v):
    return (1.0 - v) ** 2.4


# frost creeping in from the edges: value noise crystals on an edge falloff
rnd = random.Random(11)
G = 24
grid = [[rnd.random() for _ in range(G + 1)] for _ in range(G + 1)]
fine = [[rnd.random() for _ in range(G * 3 + 1)] for _ in range(G * 3 + 1)]


def vnoise(tab, n, u, v):
    x, y = u * n, v * n
    i, j = int(x), int(y)
    fx, fy = x - i, y - j
    i1, j1 = min(i + 1, n), min(j + 1, n)
    a = tab[j][i] * (1 - fx) + tab[j][i1] * fx
    b = tab[j1][i] * (1 - fx) + tab[j1][i1] * fx
    return a * (1 - fy) + b * fy


def frost(u, v):
    x, y = abs(u - 0.5) * 2, abs(v - 0.5) * 2
    edge = max(x ** 3, y ** 3) * 0.7 + (x * x + y * y) * 0.25
    n = 0.6 * vnoise(grid, G, u, v) + 0.4 * vnoise(fine, G * 3, u, v)
    a = smooth(0.35, 0.95, edge + (n - 0.5) * 0.45)
    # sparkly crystal edges
    return a * (0.65 + 0.35 * n)


save_alpha('vignette.tga', (256, 256), vignette)
save_grey('topglow.tga', (16, 128), topglow)
save_alpha('frost.tga', (256, 256), frost)

SHADERS = """// rearmed v4 random events + slow motion screen effects (generated by tools/make_events_gfx.py)

rearmed/evFilter
{
	nopicmip
	{
		map $whiteimage
		blendFunc GL_DST_COLOR GL_ZERO
		rgbGen vertex
	}
}

rearmed/evFlash
{
	nopicmip
	{
		map $whiteimage
		blendFunc GL_ONE GL_ONE
		rgbGen vertex
	}
}

rearmed/evVignette
{
	nopicmip
	nomipmaps
	{
		clampmap gfx/rearmed/events/vignette.tga
		blendFunc blend
		rgbGen vertex
		alphaGen vertex
	}
}

rearmed/evTopGlow
{
	nopicmip
	nomipmaps
	{
		clampmap gfx/rearmed/events/topglow.tga
		blendFunc GL_ONE GL_ONE
		rgbGen vertex
	}
}

rearmed/evFrost
{
	nopicmip
	nomipmaps
	{
		clampmap gfx/rearmed/events/frost.tga
		blendFunc blend
		rgbGen vertex
		alphaGen vertex
	}
}
"""
(ROOT / 'scripts').mkdir(parents=True, exist_ok=True)
(ROOT / 'scripts' / 'rearmed_events.shader').write_text(SHADERS.replace('\n', '\r\n'), newline='')
print('events gfx done')
