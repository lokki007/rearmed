# ------------------------------------------------------------------ sound helpers
def write(name, samples, level=0.9):
    SND.mkdir(parents=True, exist_ok=True)
    peak = max(1e-9, max(abs(s) for s in samples))
    with wave.open(str(SND / name), 'wb') as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(b''.join(struct.pack('<h', int(max(-1.0, min(1.0, s / peak * level)) * 32767)) for s in samples))


def n(sec):
    return int(RATE * sec)


def env(t, attack, decay):
    return min(1.0, t / attack if attack > 0 else 1.0) * math.exp(-t / decay)


def mix(out, at, samples, gain=1.0):
    j0 = n(at)
    for i, s in enumerate(samples):
        if 0 <= j0 + i < len(out):
            out[j0 + i] += gain * s


def bell(f, length, decay, bright=1.0):
    return [(math.sin(2 * math.pi * f * i / RATE) + 0.45 * bright * math.sin(2 * math.pi * f * 2.76 * i / RATE)
             + 0.2 * bright * math.sin(2 * math.pi * f * 5.4 * i / RATE)) * env(i / RATE, 0.002, decay) for i in range(n(length))]


def saw(f, length, attack, decay, harm=8, vib=0.0):
    out, ph = [], 0.0
    for i in range(n(length)):
        t = i / RATE
        ph += 2 * math.pi * f * (1 + vib * math.sin(2 * math.pi * 5.5 * t)) / RATE
        s = sum(math.sin(ph * h) / h for h in range(1, harm + 1))
        out.append(s * env(t, attack, decay))
    return out


def noise(length, seed, lp=0.5):
    r = random.Random(seed)
    y, out = 0.0, []
    for _ in range(n(length)):
        y += lp * (r.uniform(-1, 1) - y)
        out.append(y)
    return out


def kick(length=0.35, f0=55):
    out, ph = [], 0.0
    for i in range(n(length)):
        t = i / RATE
        f = f0 * (1 + 3.0 * math.exp(-t / 0.03))
        ph += 2 * math.pi * f / RATE
        out.append(math.sin(ph) * env(t, 0.001, 0.12))
    return out


def semi(base, s):
    return base * 2 ** (s / 12.0)


# ------------------------------------------------------------------ sounds
def tier_sting(t):
    # a rising chord stab per tier: I minor-ish pluck, II brighter, III power + octave, IV big stab + kick
    roots = [0, 220.0, 261.6, 311.1, 370.0]
    root = roots[t]
    L = 0.9 + 0.15 * t
    out = [0.0] * n(L)
    chord = [0, 7, 12] if t < 3 else [0, 4, 7, 12, 16] if t == 3 else [0, 4, 7, 11, 12, 16, 19]
    # quick arpeggio up, then the chord held
    for k, s in enumerate(chord):
        mix(out, 0.035 * k, saw(semi(root, s), L - 0.035 * k, 0.004, 0.25 + 0.08 * t, 6, 0.004), 0.22)
    for k, s in enumerate([12, 16, 19, 24][:1 + t]):
        mix(out, 0.06 + 0.05 * k, bell(semi(root * 2, s), 0.5, 0.12), 0.25)
    if t >= 3:
        mix(out, 0.0, kick(0.4, 50), 0.9)
    mix(out, 0.0, [s * env(i / RATE, 0.001, 0.02) for i, s in enumerate(noise(0.08, 11 + t, 0.8))], 0.4)
    return out


def cashout():
    # a cascade of coin ticks climbing, then a resolving chime
    out = [0.0] * n(1.3)
    scale = [0, 2, 4, 7, 9, 12, 14, 16, 19, 21, 24]
    for k, s in enumerate(scale):
        mix(out, 0.045 * k, bell(semi(1318.5, s), 0.18, 0.04, 0.8), 0.3)
    for k, s in enumerate([0, 4, 7, 12]):
        mix(out, 0.5 + 0.01 * k, bell(semi(659.3, s), 0.8, 0.3, 0.6), 0.3)
    mix(out, 0.5, kick(0.3, 70), 0.5)
    return out


def crit(seed):
    # crunch: a bone-crack noise burst with a low thump, then a bright metallic ping
    r = random.Random(seed)
    out = [0.0] * n(0.55)
    crack = noise(0.09, seed, 0.95)
    mix(out, 0.0, [s * env(i / RATE, 0.0005, 0.018) * (1.0 if (i // 37) % 2 else -0.6) for i, s in enumerate(crack)], 1.0)
    mix(out, 0.012, [s * env(i / RATE, 0.001, 0.03) for i, s in enumerate(noise(0.12, seed + 1, 0.3))], 0.8)
    mix(out, 0.0, kick(0.2, 70 + 10 * seed), 0.6)
    f = 2093.0 * (1.0 + 0.06 * r.uniform(-1, 1))
    mix(out, 0.03, bell(f, 0.5, 0.11, 1.4), 0.55)
    mix(out, 0.05, bell(f * 1.5, 0.4, 0.08, 1.0), 0.3)
    return out


def berserk():
    # a roar: pitch-dropping saw growl + noise, a minor power chord swelling, a hit
    L = 1.6
    out = [0.0] * n(L)
    ph = 0.0
    for i in range(n(1.0)):
        t = i / RATE
        f = 140 * (1 + 0.8 * math.exp(-t / 0.15)) * (1 + 0.03 * math.sin(2 * math.pi * 23 * t))
        ph += 2 * math.pi * f / RATE
        s = sum(math.sin(ph * h) / h for h in range(1, 12))
        out[i] += 0.35 * s * env(t, 0.01, 0.35)
    mix(out, 0.0, [s * env(i / RATE, 0.005, 0.25) for i, s in enumerate(noise(0.9, 21, 0.4))], 0.5)
    for k, s in enumerate([0, 7, 12, 15]):
        mix(out, 0.08, saw(semi(110, s), L - 0.1, 0.12, 0.6, 7, 0.006), 0.18)
    mix(out, 0.0, kick(0.5, 45), 1.0)
    return out


def overdrive():
    # an electric whoosh rising, zaps, then a bright major chord
    L = 1.4
    out = [0.0] * n(L)
    r = random.Random(31)
    y1 = y2 = 0.0
    for i in range(n(0.8)):
        t = i / RATE
        k = t / 0.8
        a = 0.03 + 0.55 * k * k
        y1 += a * (r.uniform(-1, 1) - y1)
        y2 += a * (y1 - y2)
        out[i] += 2.2 * (y1 - y2) * math.sin(math.pi * k) ** 1.2
    ph = 0.0
    for i in range(n(0.7)):
        t = i / RATE
        f = 200 + 1400 * (t / 0.7) ** 2
        ph += 2 * math.pi * f / RATE
        out[i] += 0.25 * (1 if math.sin(ph) > 0 else -1) * env(t, 0.02, 0.5) * (0.5 + 0.5 * math.sin(2 * math.pi * 31 * t))
    for k, s in enumerate([0, 4, 7, 12, 16]):
        mix(out, 0.55 + 0.02 * k, saw(semi(392.0, s), 0.8, 0.005, 0.35, 5), 0.15)
        mix(out, 0.55 + 0.04 * k, bell(semi(784.0, s), 0.5, 0.15), 0.18)
    return out


def hum(kind):
    # a seamless 2 s loop: berserk = a pulsing low minor chord (beat at 4 Hz); overdrive = a bright
    # buzzing arpeggio pad. Every partial completes whole cycles in 2 s so the loop has no seam.
    L = 2.0
    N = n(L)
    out = [0.0] * N
    if kind == 'berserk':
        freqs = [55.0, 82.5, 110.0, 131.0, 165.0]
        for i in range(N):
            t = i / RATE
            pulse = 0.55 + 0.45 * math.sin(2 * math.pi * 4.0 * t) ** 2
            s = 0.0
            for j, f in enumerate(freqs):
                f = round(f * L) / L
                s += math.sin(2 * math.pi * f * t) / (1 + j * 0.6) + 0.3 * math.sin(2 * math.pi * 2 * f * t) / (1 + j)
            out[i] = s * pulse
    else:
        notes = [392.0, 493.9, 587.3, 784.0]
        for i in range(N):
            t = i / RATE
            step = int(t * 8) % 4
            s = 0.0
            for j, f in enumerate([196.0, 293.7]):
                f = round(f * L) / L
                s += 0.5 * math.sin(2 * math.pi * f * t) + 0.15 * (1 if math.sin(2 * math.pi * f * t) > 0 else -1)
            f = round(notes[step] * L) / L
            frac = (t * 8) % 1.0
            s += 0.45 * math.sin(2 * math.pi * f * t) * math.exp(-frac / 0.35)
            out[i] = s * (0.8 + 0.2 * math.sin(2 * math.pi * 16 * t))
    return out


def spike_end():
    out = [0.0] * n(0.9)
    ph = 0.0
    for i in range(n(0.8)):
        t = i / RATE
        f = 600 * math.exp(-t / 0.25) + 60
        ph += 2 * math.pi * f / RATE
        out[i] += sum(math.sin(ph * h) / h for h in range(1, 6)) * env(t, 0.005, 0.3)
    mix(out, 0.0, bell(880, 0.5, 0.15), 0.3)
    return out


def shimmer(rarity):
    # a sparkle glissando, longer and fuller with the rarity; legendary adds a held major chord
    r = random.Random(40 + rarity)
    L = 0.7 + 0.35 * rarity
    out = [0.0] * n(L)
    base = [1568.0, 1318.5, 1174.7, 1046.5][rarity]
    count = 5 + 3 * rarity
    for k in range(count):
        s = [0, 2, 4, 7, 9, 12, 14, 16, 19, 21, 24, 26, 28][k % 13]
        mix(out, 0.035 * k + r.uniform(0, 0.01), bell(semi(base, s), 0.35, 0.09, 1.2), 0.25)
    if rarity >= 2:
        for k, s in enumerate([0, 4, 7] if rarity == 2 else [0, 4, 7, 11, 12]):
            mix(out, 0.1, saw(semi(base / 4, s), L - 0.12, 0.15, 0.4, 4, 0.01), 0.1)
    return out


SCALE = [0, 2, 4, 7, 9, 12, 14, 16, 19, 21, 24, 26]


def tickhot(step):
    # the frenzy layer on a gem tick: an octave up, brighter, a small sparkle
    f = 2093.0 * 2 ** (SCALE[step] / 12.0)
    out = [0.0] * n(0.14)
    mix(out, 0.0, bell(f, 0.14, 0.03, 1.3), 1.0)
    mix(out, 0.0, [s * 0.4 for s in noise(0.008, 70 + step, 0.95)], 1.0)
    return out


def main():
    save_rgb('beam.tga', (64, 256), beam)
    save_rgb('streak.tga', (64, 64), streak)
    save_rgb('glint.tga', (64, 64), glint)
    save_rgb('ring.tga', (64, 64), ring_thin)
    save_rgb('edgeh.tga', (64, 4), lambda u, v: (1.0 - u) ** 2.4)
    save_rgb('edgev.tga', (4, 64), lambda u, v: (1.0 - v) ** 2.4)
    (ROOT / 'scripts').mkdir(parents=True, exist_ok=True)
    (ROOT / 'scripts' / 'rearmed_frenzy.shader').write_text(SHADERS)

    for t in range(1, 5):
        write('tier%i.wav' % t, tier_sting(t), 0.8 + 0.04 * t)
    write('cashout.wav', cashout(), 0.85)
    write('crit1.wav', crit(1), 0.95)
    write('crit2.wav', crit(2), 0.95)
    write('berserk.wav', berserk(), 0.95)
    write('overdrive.wav', overdrive(), 0.9)
    write('hum_berserk.wav', hum('berserk'), 0.5)
    write('hum_overdrive.wav', hum('overdrive'), 0.45)
    write('spike_end.wav', spike_end(), 0.75)
    for r in range(4):
        write('shimmer%i.wav' % r, shimmer(r), 0.55 + 0.1 * r)
    for s in range(12):
        write('tickhot%i.wav' % s, tickhot(s), 0.95)
    print('frenzy assets written:', GFX, SND)


if __name__ == '__main__':
    main()
