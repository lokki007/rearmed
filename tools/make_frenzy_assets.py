"""DESCENT round 3 FRENZY assets (ds-frenzy): textures + shaders + synthesized sounds.

Textures  assets/gfx/rearmed/frenzy/*.tga   (loot beam, its streaks, crit glint, screen edge washes)
Shaders   assets/scripts/rearmed_frenzy.shader
Sounds    assets/sound/rearmed/frenzy/*.wav (22 kHz 16-bit mono): chain tier stings, the cash-out,
          crit crunches, BERSERK / OVERDRIVE starts, their hum loops, the power-down, beam
          shimmers by rarity, the hot pickup tick layer.
All generated here (our own content). Run: python tools/make_frenzy_assets.py
"""
import math, random, struct, wave, pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent / 'assets'
GFX = ROOT / 'gfx' / 'rearmed' / 'frenzy'
SND = ROOT / 'sound' / 'rearmed' / 'frenzy'
RATE = 22050


# ------------------------------------------------------------------ textures
def save_rgb(name, size, fn):
    w, h = size
    im = Image.new('RGBA', size)
    px = im.load()
    for y in range(h):
        for x in range(w):
            v = max(0.0, min(1.0, fn((x + 0.5) / w, (y + 0.5) / h)))
            c = int(v * 255 + 0.5)
            px[x, y] = (c, c, c, 255)
    GFX.mkdir(parents=True, exist_ok=True)
    im.save(GFX / name)


def beam(u, v):
    # across: a hot core and a soft halo; up (v = 0 is the top): fades out, a soft foot
    x = u - 0.5
    across = 0.85 * math.exp(-(x / 0.07) ** 2) + 0.45 * math.exp(-(x / 0.22) ** 2)
    up = (v ** 1.6) * (1.0 - math.exp(-((1.0 - v) / 0.04)))
    return across * up * 1.15


rnd = random.Random(5)
STREAK = [rnd.uniform(0.2, 1.0) for _ in range(16)]


def streak(u, v):
    # thin vertical light streaks that scroll up the beam (tcMod scroll); tiles vertically
    x = u * 16
    i = int(x) % 16
    f = x - int(x)
    col = math.exp(-((f - 0.5) / 0.18) ** 2) * STREAK[i]
    wob = 0.5 + 0.5 * math.sin(2 * math.pi * (v * 2 + STREAK[(i + 3) % 16]))
    return col * wob * math.exp(-((u - 0.5) / 0.3) ** 2)


def glint(u, v):
    # a four-point star with a round hot core
    x, y = u - 0.5, v - 0.5
    r = math.hypot(x, y)
    star = math.exp(-(abs(x) / 0.025) ** 1.3) * math.exp(-(abs(y) / 0.42) ** 2) \
        + math.exp(-(abs(y) / 0.025) ** 1.3) * math.exp(-(abs(x) / 0.42) ** 2)
    core = math.exp(-(r / 0.09) ** 2)
    return min(1.0, 0.8 * star + core)


def ring_thin(u, v):
    r = math.hypot(u - 0.5, v - 0.5)
    return math.exp(-((r - 0.42) / 0.035) ** 2)


