"""Kill cam / replay panel textures + shaders (gfx/rearmed/killcam/*.tga,
scripts/rearmed_killcam.shader). ds-killcam worker, 0.5.0."""
import math, pathlib, random
from PIL import Image, ImageFilter

ROOT = pathlib.Path(__file__).resolve().parent.parent / 'assets'
GFX = ROOT / 'gfx' / 'rearmed' / 'killcam'
GFX.mkdir(parents=True, exist_ok=True)
random.seed(1977)

# film grain: grey 128 +- a little, slightly blurred so it reads as grain, not pixel noise.
# Used with blendFunc GL_DST_COLOR GL_SRC_COLOR (2 * src * dst): 128 = no change. Tiles.
N = 256
im = Image.new('L', (N, N))
px = im.load()
for y in range(N):
    for x in range(N):
        px[x, y] = max(0, min(255, int(128 + random.gauss(0, 20))))
im = im.filter(ImageFilter.GaussianBlur(0.6))
Image.merge('RGBA', (im, im, im, Image.new('L', (N, N), 255))).save(GFX / 'grain.tga')

# vignette for the panel: black, alpha grows towards the edges and corners (clamped, any aspect)
W, H = 256, 160
v = Image.new('RGBA', (W, H))
vp = v.load()
for y in range(H):
    for x in range(W):
        u = (x + 0.5) / W * 2 - 1
        w = (y + 0.5) / H * 2 - 1
        d = math.sqrt((abs(u) ** 2.6 + abs(w) ** 2.6) / 2) ** (1 / 2.6) * math.sqrt(2)
        a = max(0.0, min(1.0, (d - 0.55) / 0.75))
        a = a * a * (3 - 2 * a)
        vp[x, y] = (0, 0, 0, int(a * 235))
v.save(GFX / 'vignette.tga')

SHADER = """// rearmed 0.5 kill cam / replay panel (generated by tools/make_killcam_gfx.py)

rearmed/kcGrain
{
	nopicmip
	{
		map gfx/rearmed/killcam/grain.tga
		blendFunc GL_DST_COLOR GL_SRC_COLOR
		rgbGen identity
	}
}

rearmed/kcVignette
{
	nopicmip
	nomipmaps
	{
		clampmap gfx/rearmed/killcam/vignette.tga
		blendFunc blend
		rgbGen vertex
		alphaGen vertex
	}
}
"""
(ROOT / 'scripts' / 'rearmed_killcam.shader').write_text(SHADER, newline='\n')
print('killcam gfx written to', GFX)
