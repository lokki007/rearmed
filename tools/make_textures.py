def save(name, size, fn):
    w, h = size
    im = Image.new('RGBA', size)
    px = im.load()
    for y in range(h):
        for x in range(w):
            v = max(0.0, min(1.0, fn((x + 0.5) / w, (y + 0.5) / h)))
            c = int(v * 255 + 0.5)
            px[x, y] = (c, c, c, 255)
    GFX.mkdir(parents=True, exist_ok=True)
    im.save(GFX / name)


# spark streak: bright core line across the width (rail core texcoord t), soft edges
save('spark.tga', (16, 32), lambda u, v: math.exp(-((v - 0.5) / 0.16) ** 2) + 0.6 * math.exp(-((v - 0.5) / 0.05) ** 2))
# round soft glow for embers and flashes
save('glow.tga', (64, 64), lambda u, v: math.exp(-(((u - .5) ** 2 + (v - .5) ** 2) ** 0.5 / 0.2) ** 2 * 1.0) * 1.1)
# shockwave ring
save('ring.tga', (128, 128), lambda u, v: math.exp(-(((((u - .5) ** 2 + (v - .5) ** 2) ** 0.5) - 0.40) / 0.05) ** 2))

def hitmarker(u, v):
    # four diagonal strokes around an empty center (alpha in the grey value)
    x, y = u - 0.5, v - 0.5
    r = (x * x + y * y) ** 0.5
    along = abs(abs(x) - abs(y))          # distance from the diagonals
    if r < 0.17 or r > 0.47:
        return 0.0
    return max(0.0, 1.0 - along / 0.045)


def save_alpha(name, size, fn):
    w, h = size
    im = Image.new('RGBA', size)
    px = im.load()
    for yy in range(h):
        for xx in range(w):
            a = max(0.0, min(1.0, fn((xx + 0.5) / w, (yy + 0.5) / h)))
            px[xx, yy] = (255, 255, 255, int(a * 255 + 0.5))
    im.save(GFX / name)


save_alpha('hitmarker.tga', (64, 64), hitmarker)
# screen edge fade for the low health pulse (alpha falls off from u=0)
save_alpha('edge.tga', (64, 4), lambda u, v: (1.0 - u) ** 2.2)


def dmgdir(k):
    # damage direction wedge: an arc segment around the center, pointing at angle k*22.5 deg (0 = up)
    ang = math.radians(k * 22.5)
    def fn(u, v):
        x, y = u - 0.5, 0.5 - v
        r = (x * x + y * y) ** 0.5
        a = math.atan2(x, y) - ang
        a = (a + math.pi) % (2 * math.pi) - math.pi
        width = 0.42 - (r - 0.30) * 1.4        # wider inside: a slight arrow shape
        if r < 0.30 or r > 0.47 or abs(a) > width:
            return 0.0
        return min(1.0, (width - abs(a)) / 0.08) * min(1.0, (0.47 - r) / 0.03)
    return fn


for k in range(16):
    save_alpha('dmgdir%02d.tga' % k, (64, 64), dmgdir(k))


def icon(name, rgb, shape):
    """64x64 HUD icon: colored glyph with a soft glow on transparent background."""
    im = Image.new('RGBA', (64, 64))
    px = im.load()
    for yy in range(64):
        for xx in range(64):
            u, v = (xx + 0.5) / 64 - 0.5, (yy + 0.5) / 64 - 0.5
            a = max(0.0, min(1.0, shape(u, v)))
            glow = max(0.0, 0.35 - (u * u + v * v) ** 0.5) * 1.2
            a = max(a, glow)
            k = 0.55 + 0.45 * a
            px[xx, yy] = (int(rgb[0] * k), int(rgb[1] * k), int(rgb[2] * k), int(255 * a))
    icons = ROOT / 'icons'
    icons.mkdir(parents=True, exist_ok=True)
    im.save(icons / name)


def drop(u, v):
    # blood drop: circle at the bottom, point at the top
    r = ((u) ** 2 + (v - 0.1) ** 2) ** 0.5
    if r < 0.24:
        return 1.0
    if -0.38 < v < 0.1 and abs(u) < 0.24 * (v + 0.38) / 0.48:
        return 1.0
    return 0.0


def chevrons(u, v):
    # two stacked forward chevrons
    out = 0.0
    for off in (-0.12, 0.12):
        d = abs(abs(v) * 0.9 - (u - off) * -1 - 0.0)
        if abs(v) < 0.3 and abs((u - off) - (0.3 - abs(v)) * 0.8 + 0.12) < 0.06:
            out = 1.0
    return out


def flame(u, v):
    # teardrop flame pointing up
    w = 0.22 * max(0.0, min(1.0, (v + 0.42) / 0.55)) ** 0.7 * (1 if v < 0.13 else max(0.0, 1 - (v - 0.13) / 0.25))
    return 1.0 if abs(u) < w and -0.42 < v < 0.38 else 0.0


