def blood_atlas(name):
    """Permanent blood pools (cgame/cg_blood.c): 2x2 atlas, 256px cells.
    Cells 0-1 (top row) are big pools, 2-3 (bottom row) splatter. Irregular
    blobs with droplets, alpha in the texture. The color is a bright red with
    some green in it: the vertex color only darkens it, toward brown-red."""
    import random
    import numpy as np
    rng = random.Random(1987)
    C = 256
    yy, xx = np.mgrid[0:C, 0:C]
    u = (xx + 0.5) / C - 0.5
    v = (yy + 0.5) / C - 0.5
    rho = np.hypot(u, v)

    def blob(cx, cy, r0, rough, harmonics=11):
        # wobbly circle, positive inside (in texture units)
        du, dv = u - cx, v - cy
        rr = np.hypot(du, dv)
        tt = np.arctan2(dv, du)
        r = np.full_like(rr, r0)
        for k in range(2, harmonics + 1):
            amp = r0 * rough * rng.uniform(0.4, 1.0) / k ** 1.3
            r += amp * np.sin(k * tt + rng.uniform(0, 2 * math.pi))
        return r - rr

    def drop(cx, cy, a, b, ang):
        # ellipse, radius a along ang and b across, positive inside
        du, dv = u - cx, v - cy
        p = du * math.cos(ang) + dv * math.sin(ang)
        q = -du * math.sin(ang) + dv * math.cos(ang)
        return (1.0 - np.hypot(p / a, q / b)) * b

    def noise():
        n = np.zeros_like(u)
        for _ in range(5):
            a = rng.uniform(0, 2 * math.pi)
            f = rng.uniform(6, 22) * 2 * math.pi
            n += np.sin((u * math.cos(a) + v * math.sin(a)) * f + rng.uniform(0, 6.3))
        return n / 5

    atlas = np.zeros((2 * C, 2 * C, 4), dtype=np.uint8)
    for cell, kind in enumerate(('pool', 'pool', 'splat', 'splat')):
        if kind == 'pool':
            body = blob(0, 0, 0.28, 0.35)
            for _ in range(rng.randint(2, 4)):          # side lobes
                a = rng.uniform(0, 2 * math.pi)
                dist = rng.uniform(0.2, 0.27)
                body = np.maximum(body, blob(dist * math.cos(a), dist * math.sin(a),
                                             rng.uniform(0.06, 0.1), 0.3, 6))
            ndrops, dmin, dmax, streak = rng.randint(12, 22), 0.34, 0.45, 0.6
        else:
            body = blob(0, 0, 0.13, 0.45)
            ndrops, dmin, dmax, streak = rng.randint(30, 45), 0.12, 0.45, 1.6
            spray = rng.uniform(0, 2 * math.pi)
        d = body.copy()
        for _ in range(ndrops):
            a = rng.uniform(0, 2 * math.pi) if kind == 'pool' else spray + rng.gauss(0, 0.9)
            dist = rng.uniform(dmin, dmax)
            f = (dist - dmin) / (dmax - dmin)
            size = 0.026 * (1 - 0.7 * f) * rng.uniform(0.4, 1.0)
            length = size * (1 + streak * f)
            dist = min(dist, 0.465 - length)
            d = np.maximum(d, drop(dist * math.cos(a), dist * math.sin(a), length, size, a))
        d = np.minimum(d, 0.47 - rho)                    # transparent border between cells
        alpha = np.clip(d * C / 1.5 + 0.5, 0, 1)
        thick = np.clip(body / 0.10, 0, 1) ** 0.7        # 0 at the rim, 1 deep in the pool
        rim = np.exp(-((body - 0.012) / 0.012) ** 2)     # darker drying ring inside the edge
        shade = (1 - 0.18 * rim) * (1 + 0.06 * noise())
        edge, deep = np.array([190, 34, 26]), np.array([125, 16, 12])
        rgb = (edge + (deep - edge) * thick[..., None]) * shade[..., None]
        a8 = alpha * (0.92 + 0.08 * thick)
        y0, x0 = (cell >> 1) * C, (cell & 1) * C
        atlas[y0:y0 + C, x0:x0 + C, :3] = np.clip(rgb, 0, 255).astype(np.uint8)
        atlas[y0:y0 + C, x0:x0 + C, 3] = np.clip(a8 * 255 + 0.5, 0, 255).astype(np.uint8)
    Image.fromarray(atlas, 'RGBA').save(GFX / name)


