"""ds-boss (DESCENT round 2): the life skull icon for the boss bar + its shader file.

Writes assets/gfx/rearmed/acts/lifeskull.tga (32x32, white skull, alpha) and
assets/scripts/rearmed_dsboss.shader (the life skull, the nemesis rim, the armoured boss sheen).
"""
import math, pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent / 'assets'


def skull(u, v):
    """coverage of a simple front-facing skull at (u, v) in 0..1 (v down)"""
    x, y = u - 0.5, v - 0.5
    # cranium: a circle, jaw: a narrower rounded box under it
    head = math.hypot(x / 0.40, (y + 0.08) / 0.36) <= 1.0
    jaw = abs(x) <= 0.22 and 0.12 <= y <= 0.40
    jaw_round = jaw and not (abs(x) > 0.16 and y > 0.34)
    a = head or jaw_round
    if not a:
        return 0.0
    # eye sockets
    for ex in (-0.15, 0.15):
        if math.hypot((x - ex) / 0.10, (y - 0.0) / 0.11) <= 1.0:
            return 0.0
    # nose: a small triangle
    if 0.10 <= y <= 0.20 and abs(x) <= (y - 0.10) * 0.45:
        return 0.0
    # teeth gaps
    if 0.30 <= y <= 0.40 and any(abs(x - tx) < 0.018 for tx in (-0.11, -0.04, 0.04, 0.11)):
        return 0.0
    return 1.0


def main():
    size = 32
    ss = 4
    im = Image.new('RGBA', (size, size))
    px = im.load()
    for j in range(size):
        for i in range(size):
            acc = 0.0
            for sj in range(ss):
                for si in range(ss):
                    acc += skull((i + (si + 0.5) / ss) / size, (j + (sj + 0.5) / ss) / size)
            a = acc / (ss * ss)
            px[i, j] = (255, 255, 255, int(a * 255 + 0.5))
    out = ROOT / 'gfx' / 'rearmed' / 'acts'
    out.mkdir(parents=True, exist_ok=True)
    im.save(out / 'lifeskull.tga')

    shader = """// ds-boss (DESCENT round 2): generated by tools/make_textures_boss.py

// the boss bar's life skulls (coloured by the HUD)
rearmed/dsLifeSkull
{
	nopicmip
	{
		clampmap gfx/rearmed/acts/lifeskull.tga
		blendFunc GL_SRC_ALPHA GL_ONE_MINUS_SRC_ALPHA
		rgbGen vertex
		alphaGen vertex
	}
}

// the nemesis: a dim dark red rim over its skin
rearmed/dsNemesisShell
{
	deformVertexes wave 100 sin 0.8 0 0 0
	{
		map textures/effects/envmapred.jpg
		blendfunc GL_ONE GL_ONE
		tcGen environment
		tcmod scroll 0.05 0.1
		rgbGen wave sin 0.32 0.06 0 0.4
	}
}

// an armoured (tanky) act boss: a cold steel sheen
rearmed/dsArmourShell
{
	deformVertexes wave 100 sin 1.2 0 0 0
	{
		map textures/effects/envmapdim.jpg
		blendfunc GL_ONE GL_ONE
		tcGen environment
		tcmod scroll 0.02 0.06
		rgbGen const ( 0.34 0.38 0.44 )
	}
}
"""
    (ROOT / 'scripts' / 'rearmed_dsboss.shader').write_text(shader, newline='\n')
    print('lifeskull.tga + rearmed_dsboss.shader written')


if __name__ == '__main__':
    main()
