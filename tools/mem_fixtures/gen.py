"""Writes the en-memory test cfgs (tools/mem_fixtures/*.cfg) for tools/mem_test.sh.
'wait 10' steps (~0.1 s real each at com_maxfps 100) so the commands the game inserts still run.
Bots are addressed by client number (1 = the first planned bot): names vary by run seed and floor.
The player's name is set to ^1Ash^7Wolf so the lines must use the in-game name (cleaned: AshWolf)."""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent


def W(sec):
    return ['wait 10'] * max(1, int(sec * 10))


HEAD = ['set com_maxfps 100', 'set cg_drawFPS 0', 'name ^1Ash^7Wolf']


def floor_start(diff=None):
    s = []
    if diff is not None:
        s += ['descent new %d' % diff] + W(0.6)
    return s + ['rlpicknode 0'] + W(10) + ['echo MARK floor', 'god', 'dsbm']


def killme(c, n=1):
    out = []
    for _ in range(n):
        out += ['prkillme %s' % c] + W(6) + ['god']
    return out


def kill(c, n=1):
    out = []
    for _ in range(n):
        out += ['prkill %s' % c] + W(4.5)
    return out


def say(k, d, fm, rm, nem=0, sec=9):
    return ['dsbm set 1 %d %d %d %d %d' % (k, d, fm, rm, nem), 'dsbm say 1'] + W(2.6) + ['screenshotJPEG'] + W(sec - 2.6)


CFGS = {
    # the tiers: bot 1's record is scripted through every tier; each greeting is logged ("BotMem: greet")
    # and goes to the chat line (g_botTaunts 2 in the harness lets 7 lines through in a minute)
    'mem_tiers.cfg': HEAD + W(3) + floor_start(3) + W(2)
    + say(0, 0, 0, 0) + say(3, 2, 2, 1) + say(7, 6, 6, 2) + say(16, 14, 29, 6) + say(16, 14, 29, 6, 2)
    + say(2, 12, 8, 3) + say(3, 9, 5, 2)
    + ['dsbm'] + W(0.5) + ['quit'],
    # real floors: run A (difficulty 4 = 1 life): floor 1 = kills both ways, a nemesis rises and is slain;
    # floor 2 = a nemesis rises, is dethroned, the run is lost (the second one outlives it);
    # run B: a nemesis rises and is still hunting; then the hall of fame + rivals screens
    'mem_flow.cfg': HEAD + W(3) + floor_start(4)
    + killme(1, 3) + ['dsnemesis level 3'] + W(1) + kill(2, 3) + kill(1)
    + ['dsbm', 'rlwin'] + W(9) + ['cmd rlpick 0'] + W(6) + floor_start()
    + killme(1, 3) + killme(2, 4) + ['dsnemesis', 'dsbm', 'rllose'] + W(18) + ['disconnect'] + W(1.5)
    + floor_start(3) + killme(2, 3) + kill(1) + ['dsbm', 'rlwin'] + W(9) + ['cmd rlpick 0'] + W(6) + floor_start()
    + W(35) + ['dsbm', 'rlwin'] + W(9) + ['disconnect'] + W(1.5)
    + ['dshall'] + W(4) + ['screenshotJPEG'] + W(0.5) + ['dshall rivals'] + W(4) + ['screenshotJPEG'] + W(0.5) + ['quit'],
    # the screens from the main menu over a recorded file (BOTS=...): hall, rivals, the Records button row
    'mem_hall.cfg': ['set com_maxfps 100'] + W(3) + ['dshall'] + W(4) + ['screenshotJPEG'] + W(0.5)
    + ['dshall rivals'] + W(4) + ['screenshotJPEG'] + W(0.5) + ['dshall records'] + W(4) + ['screenshotJPEG'] + W(0.5) + ['quit'],
}

for name, lines in CFGS.items():
    (HERE / name).write_text('// en-memory test (generated by gen.py)\n' + '\n'.join(lines) + '\n', newline='\n')
    print(name, len(lines))
