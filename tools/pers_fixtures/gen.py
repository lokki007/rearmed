"""Writes the en-personality test cfgs (tools/pers_fixtures/*.cfg). 'wait 10' steps at com_maxfps 100
(~0.1 s real each) so commands the game inserts still run. Used by tools/pers_test.sh."""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent


def W(sec):
    return ['wait 10'] * max(1, int(sec * 10))


HEAD = ['set com_maxfps 100', 'set cg_drawFPS 0', 'set cg_debugEvents 0']
BOTS = ['addbot sarge 3', 'addbot visor 3', 'addbot doom 3', 'addbot major 3', 'addbot slash 3']

CFGS = {
    # FFA (all modes): 5 bots, the player idles at a spawn (dies a lot), timescale 2 for 4 game minutes
    'taunt_ffa.cfg': HEAD + W(3) + BOTS + W(4) + ['set timescale 2'] + W(240) + ['prstat'] + W(0.2)
    + ['set timescale 1', 'prstat'] + W(0.5) + ['quit'],
    # DESCENT floor A: bots fight 2 game minutes (the player idles, dies), then the floor is won
    'vet_a.cfg': HEAD + W(4) + ['dsvet', 'set timescale 2'] + W(120) + ['set timescale 1', 'prstat', 'rlwin'] + W(3)
    + ['dsvet'] + W(0.5) + ['quit'],
    # DESCENT floor B: the roster comes back; the intro strip, the TAB scoreboard, a shoulder light up close
    'vet_b.cfg': HEAD + W(1.6) + ['screenshotJPEG'] + W(2.5) + ['dsvet', 'god'] + W(2) + ['+scores'] + W(0.6)
    + ['screenshotJPEG'] + W(0.3) + ['-scores', 'bot_pause 1', 'set cg_drawGun 0', 'set cg_fov 40',
    'setviewpos -288 -376 40 0', 'teleport 1 -40 -390 24 180', 'teleport 2 -40 -300 24 180', 'set cg_fov 30'] + W(1.5)
    + ['screenshotJPEG'] + W(0.5) + ['bot_pause 0', 'set cg_fov 90', 'set timescale 2'] + W(60) + ['set timescale 1', 'prstat', 'rlwin'] + W(3)
    + ['dsvet'] + W(0.5) + ['quit'],
    # DESCENT nemesis: Visor (the last planned bot) kills the player 5 more times -> level 6, then the player
    # takes revenge on bot 1 and slays the nemesis
    'nemesis.cfg': HEAD + W(6) + ['god', 'dsnemesis'] + W(4)
    + ['prkillme Visor'] + W(8) + ['prkillme Visor'] + W(8) + ['prkillme Visor'] + W(4) + ['screenshotJPEG'] + W(4)
    + ['prkillme Visor'] + W(8) + ['prkillme Visor'] + W(4) + ['screenshotJPEG'] + W(4) + ['dsnemesis', 'prkillme Doom'] + W(8)
    + ['prkill Doom'] + W(1.5) + ['screenshotJPEG'] + W(4) + ['prkill Visor'] + W(1.5) + ['screenshotJPEG'] + W(4)
    + ['dsnemesis', 'prstat'] + W(0.5) + ['quit'],
    # telegraph shouts by a forced DSEF_TELEGRAPH edge (128) + one natural minute
    'shout.cfg': HEAD + W(4) + ['god'] + sum([['prflag 1 128 1'] + W(0.5) + ['prflag 1 128 0'] + W(7)
    + ['prflag 2 128 1'] + W(0.3) + ['prflag 2 128 0'] + W(0.5) for _ in range(3)], [])
    + ['set timescale 2'] + W(30) + ['set timescale 1', 'prstat'] + W(0.5) + ['quit'],
}

for name, lines in CFGS.items():
    (HERE / name).write_text('// en-personality test (generated by gen.py)\n' + '\n'.join(lines) + '\n', newline='\n')
    print(name, len(lines))
