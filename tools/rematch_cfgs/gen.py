# en-rematch: writes the BOSS REMATCH test cfgs (python tools/rematch_cfgs/gen.py)
# Times are in "ticks" of `wait 10` lines (many short waits: a long wait holds back commands the game inserts, like dsrmend).
import os

HERE = os.path.dirname(os.path.abspath(__file__))
HEAD = ["set com_maxfps 60", "set ui_rlDevmap 1", "set cg_dsIntro 1", "set g_dsBossTime 300", "set g_dsBossMode 0"]


def w(n):
    return ["wait 10"] * n


def fight(boss, mask, fight_ticks, shots_mid=0, god_at=300):
    out = ["dsrematch %d %d" % (boss, mask)] + w(god_at) + ["god"] + w(20)
    for _ in range(shots_mid):
        out += ["screenshotJPEG"] + w(20)
    out += w(fight_ticks) + ["dskillboss"] + w(150) + ["screenshotJPEG"] + w(20)
    return out


def write(name, lines):
    with open(os.path.join(HERE, name), "w", newline="\n") as f:
        f.write("// en-rematch test (generated by gen.py)\n" + "\n".join(HEAD + lines) + "\n")


# locked: no boss beaten; the screen, a refused launch, the table
write("rm_locked.cfg", w(60) + ["dsrematch"] + w(80) + ["screenshotJPEG"] + w(10) + ["dsrematch 1 0", "dsrminfo"] + w(20) + ["quit"])

# two heats: the screen (2 unlocked, 2 locked), heat 0 then heat 13 (all but ONE LIFE), results + the HUD line
write("rm_fights.cfg", w(60) + ["dsrematch"] + w(80) + ["screenshotJPEG"] + w(10)
      + fight(1, 0, 150)
      + fight(1, 0x3f, 120, shots_mid=2)
      + ["dsrminfo"] + w(10) + ["quit"])

# ONE LIFE + GLASS (80, heat 5): the halved health on the HUD, then die once -> FALLEN; then heat 0 again (slower: the gap to the best), the table
write("rm_onelife.cfg", w(60)
      + ["dsrematch 1 80"] + w(300) + ["screenshotJPEG"] + w(150) + ["screenshotJPEG", "kill"] + w(40) + ["screenshotJPEG"] + w(120) + ["screenshotJPEG"] + w(10)
      + fight(1, 0, 320)
      + ["dsrminfo"] + w(10) + ["quit"])

# FURY measured: 90 s of heat 0, then 90 s of FURY alone (god: count the telegraphs per minute in games.log)
write("rm_pace.cfg", w(60) + fight(1, 0, 700, god_at=120) + fight(1, 2, 700, god_at=120) + ["dsrminfo"] + w(10) + ["quit"])

# the entry: the hub's bottom row (PRACTICE / REMATCH), the practice screen with its REMATCH button
write("rm_entry.cfg", w(60) + ["descent"] + w(120) + ["screenshotJPEG"] + w(10) + ["dsbossprac"] + w(80) + ["screenshotJPEG"] + w(10) + ["quit"])
