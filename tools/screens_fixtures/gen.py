"""Writes the en-screens cfgs for tools/screens_test.sh. 'wait 10' steps at com_maxfps 100 (~0.1 s each;
longer at 7680x2160 when the frame rate drops, so shots are ordered, not timed)."""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
NEMESIS = 'Sarge'          # a bot on the seed-4242 floor (screens_test.sh probe.cfg lists them)


def W(sec):
    return ['wait 10'] * max(1, int(sec * 10))


HEAD = ['set cg_drawFPS 0'] + W(8) + ['god', 'notarget', 'bot_pause 1', 'dstypes']
SHOT = ['screenshotJPEG']

CFGS = {
    'probe.cfg': HEAD + W(1) + ['dstypes', 'quit'],
    # typed + affixed bots in a line, tells on, then every edge callout at once, then hit feel
    'fight.cfg': HEAD + W(1) + ['dslineup 330'] + W(1)
    + ['dsaffix give 1 frost', 'dsaffix give 2 fire', 'dsaffix give 3 vampiric', 'dsaffix give 4 regen']
    + W(0.5) + ['dstypeact sniper tell', 'dstypeact shield shieldup', 'dstypeact kamikaze tell', 'dstypeact medic tell']
    + W(1) + SHOT
    # callouts: nemesis (acts + personality), thief, bestiary, champion pack, frost on you
    + [f'dsnemesis {NEMESIS} 3', 'btthief give 2', 'dsbstmeet sniper', 'dsbstmeet frost', 'dschampions', 'dsaffix frost']
    + W(0.6) + SHOT + W(1.2) + SHOT
    + ['dsambush'] + W(1.5) + SHOT + W(4) + SHOT
    # hit feel
    + ['dslineup 260', 'hftest 1 stagger', 'hftest 2 decap', 'hftest 3 crawl', 'hftest 4 larm', 'hftest 5 armor 40'] + W(0.4) + SHOT
    + W(1.5) + SHOT + ['quit'],
    # the F10 menu tabs (the main menu, no map)
    'menu.cfg': W(6) + ['rearmed 7'] + W(4) + SHOT + ['rearmed 8'] + W(4) + SHOT + ['quit'],
}

for name, lines in CFGS.items():
    (HERE / name).write_text('// en-screens (generated by gen.py)\n' + '\n'.join(lines) + '\n', newline='\n')
    print(name, len(lines))

# UI screens (menu mode): the bestiary grid, the daily floor map
EXTRA_CFGS = {
    'bestiary.cfg': W(6) + ['descent collection 9'] + W(4) + SHOT + ['quit'],
    'dailymap.cfg': W(6) + ['set ds_dailyDate 20261013', 'dsdaily start'] + W(5) + SHOT + ['quit'],
}
for name, lines in EXTRA_CFGS.items():
    (HERE / name).write_text('// en-screens (generated by gen.py)\n' + '\n'.join(lines) + '\n', newline='\n')
    print(name, len(lines))
