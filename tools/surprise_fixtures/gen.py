"""Writes the ds-surprise test cfgs. Waits are split into 'wait 10' steps at com_maxfps 100 so commands
the game inserts (g_dsSurShots screenshots, extra bots) run within ~0.1 s instead of after a long wait."""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent


def W(sec):
    return ['wait 10'] * max(1, int(sec * 10))


HEAD = ['set com_maxfps 100', 'set cg_drawFPS 0', 'set g_dsSurShots 1'] + W(4) + ['god', 'dssurprise']

CFGS = {
    # a forced ambush: warning, landing, its first attack, the player's kill
    'amb_dev.cfg': HEAD + ['dsambush %ARCH%'] + W(13) + ['dssurprise', 'dssurprise kill ambush'] + W(2.5)
    + ['dssurprise', 'dssurprise sim'] + W(0.5) + ['quit'],
    # a forced ambush that lives longer (its attacks)
    'amb_long.cfg': ['set com_maxfps 100', 'set cg_drawFPS 0'] + W(4) + ['god', 'dsambush %ARCH%'] + W(60) + ['dssurprise', 'dssurprise kill ambush'] + W(2) + ['quit'],
    # the natural ambush: no dev trigger, timescale 2 (bots ok at <= 2), the leader's frags or 80 s start it
    'amb_nat.cfg': ['set com_maxfps 100', 'set cg_drawFPS 0', 'set g_dsSurShots 1'] + W(4) + ['god', 'set timescale 2']
    + W(130) + ['dssurprise', 'set timescale 1', 'dssurprise kill ambush'] + W(2) + ['dssurprise', 'rlstate'] + W(0.5) + ['quit'],
    # the golden meteor, then a bot uprising
    'events.cfg': HEAD + ['dsevent goldmeteor'] + W(14) + ['dssurprise look gold'] + W(1) + ['dsevent uprising'] + W(20)
    + ['dssurprise kill fodder'] + W(1) + ['dssurprise kill fodder'] + W(12) + ['dssurprise', 'dsevent eclipse'] + W(3)
    + ['dsevent bounty'] + W(3) + ['dssurprise kill bounty'] + W(2) + ['dssurprise'] + W(0.5) + ['quit'],
    # the ghost of a past run: warning, landing, the player's kill
    'ghost.cfg': HEAD + ['dsghost'] + W(10) + ['dssurprise', 'dssurprise kill ghost'] + W(3) + ['dssurprise'] + W(0.5) + ['quit'],
    # a floor modifier from the run file: BLACKOUT with gems around, then rlstate (health / armour), a win
    'mod.cfg': HEAD + ['dsgems 40 14'] + W(1) + ['screenshotJPEG'] + W(1) + ['rlstate'] + W(1) + ['rlwin'] + W(4) + ['quit'],
}

for name, lines in CFGS.items():
    (HERE / name).write_text('// ds-surprise test (generated by gen.py)\n' + '\n'.join(lines) + '\n', newline='\n')
    print(name, len(lines))
