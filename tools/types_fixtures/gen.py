"""Writes the en-types (enemy archetypes) test cfgs for tools/types_test.sh. Waits are 'wait 10' steps at
com_maxfps 100 (~0.1 s each) so commands the game inserts (g_dsTypesShots screenshots) run promptly."""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent


def W(sec):
    return ['wait 10'] * max(1, int(sec * 10))


HEAD = ['set com_maxfps 100', 'set cg_drawFPS 0'] + W(7) + ['god']

CFGS = {
    # every type in a row in front of the player (bots paused): their looks side by side
    'look.cfg': HEAD + ['notarget', 'dstypes'] + W(3) + ['bot_pause 1', 'dslineup 210'] + W(1.5) + ['screenshotJPEG']
    + W(0.5) + ['dslineup 300'] + W(1.5) + ['screenshotJPEG'] + W(0.5) + ['dslineup 120'] + W(1.5) + ['screenshotJPEG']
    + W(0.5) + ['dstypes'] + W(0.5) + ['quit'],
    # the tells on paused bots (the wind-up looks without the attacks): sniper laser + glint, raised shield,
    # kamikaze fuse glow, summoner ring, medic light, juggernaut size, mimic ink
    'tells.cfg': ['set com_maxfps 100', 'set cg_drawFPS 0'] + W(6) + ['bot_pause 1', 'god', 'notarget', 'dslineup 230'] + W(1)
    + ['dstypeact sniper tell', 'dstypeact shield shieldup', 'dstypeact kamikaze tell', 'dstypeact summoner tell'] + W(0.8)
    + ['screenshotJPEG'] + W(0.5) + ['dslineup 340', 'dstypeact sniper tell', 'dstypeact kamikaze tell', 'dstypeact summoner tell'] + W(0.8)
    + ['screenshotJPEG'] + W(0.5) + ['set cg_thirdPerson 1', 'set cg_thirdPersonRange 180', 'set cg_thirdPersonAngle 160'] + W(0.5)
    + ['screenshotJPEG'] + W(0.5) + ['set cg_thirdPerson 0', 'dstypes', 'quit'],
    # the natural mix per act (the planner over 20 seeds per row; no bots involved), the floor's own plan
    'sim.cfg': ['set com_maxfps 100'] + W(5) + ['dstypesim 1 4 20', 'dstypesim 4 5 20 1', 'dstypesim 8 5 20', 'dstypesim 10 6 20 1',
    'dstypesim 14 6 20', 'dstypesim 16 7 20 1', 'dstypesim 20 7 20 1', 'dstypesim 26 8 20 1', 'dstypes'] + W(1) + ['quit'],
    # the names at the edges: the versus intro / arrival strip (run with EXTRA="+set cg_dsIntro 1") and the TAB rows
    'intro.cfg': ['set com_maxfps 100', 'set cg_drawFPS 0'] + W(6) + ['god', 'notarget', 'dsintro'] + W(1.4) + ['screenshotJPEG'] + W(1.2)
    + ['screenshotJPEG'] + W(2) + ['dsintro loading 3000'] + W(0.6) + ['screenshotJPEG'] + W(5) + ['+scores'] + W(0.6)
    + ['screenshotJPEG'] + W(0.3) + ['-scores', 'dstypes'] + W(0.5) + ['quit'],
    # the types fight (the player in god mode standing at its spawn): telegraphs, heals, blasts, blinks,
    # raises; forced blinks at the end for distance samples; the counters
    'behave.cfg': HEAD + ['dstypes'] + W(70) + ['dstypestats', 'dstypes'] + W(0.5)
    + sum([['dstypeact blinker blink'] + W(0.6) for _ in range(12)], []) + ['dstypestats'] + W(0.5) + ['quit'],
    # a kamikaze: its fuse lit on purpose, then one killed early (the pop)
    'kami.cfg': HEAD + ['dstypes'] + W(4) + ['dstypeact kamikaze fuse'] + W(3) + ['dstypestats'] + W(20) + ['dstypestats', 'quit'],
}

for name, lines in CFGS.items():
    (HERE / name).write_text('// en-types test (generated by gen.py)\n' + '\n'.join(lines) + '\n', newline='\n')
    print(name, len(lines))
